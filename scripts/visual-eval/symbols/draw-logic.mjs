/** Draw visual-eval/symbols/logic/ — the ANSI logic symbols in the logic/ansi exemplar's style.
 *
 *   node scripts/visual-eval/symbols/draw-logic.mjs
 *
 * Constants are lifted from visual-eval/exemplars/logic/ansi/ideal.svg (1 unit = 1 exemplar px):
 * every gate on one 60 x 48 body box, outlines #1E293B at 1.5 filled white, wires at 1.25 with
 * square caps, inversion bubbles r = 5 tangent to the nose, junction dots r = 3.5. Symbols the
 * exemplar does not contain are built from the same parts.
 *
 * Library-wide rules (IEEE Std 91-1984 distinctive shapes):
 * - The outline is the type. No gate carries its name as text.
 * - AND is a flat back and a true semicircle; OR a concave back and two curves meeting at the
 *   nose; XOR adds a second back arc 9 units out, and its inputs stop on that outer arc.
 * - Every gate shows 12-unit input and output stubs at the exemplar's 24-unit input pitch, so
 *   the sheet shows where wires attach.
 */
import { writeSet } from "./lib.mjs";

const INK = "#1E293B";
const W_BODY = 1.5, W_WIRE = 1.25;
const STUB = 12;

const shape = (d, fill = "#FFFFFF") => `<path d="${d}" fill="${fill}" stroke="${INK}" stroke-width="${W_BODY}" stroke-linejoin="round"/>`;
const wire = (x1, y1, x2, y2) => `<path d="M ${x1} ${y1} L ${x2} ${y2}" fill="none" stroke="${INK}" stroke-width="${W_WIRE}" stroke-linecap="square"/>`;
const bubble = (cx, cy) => `<circle cx="${cx}" cy="${cy}" r="5" fill="#FFFFFF" stroke="${INK}" stroke-width="${W_BODY}"/>`;

// Bodies on the exemplar's box: back at x = -30, nose at x = 30, height 48, inputs at y = ±12.
const AND_BODY = "M -30 -24 H 6 A 24 24 0 0 1 6 24 H -30 Z";
const OR_BODY = "M -30 -24 Q -16 0 -30 24 C -4 22 16 14 30 0 C 16 -14 -4 -22 -30 -24 Z";
const XOR_BACK = "M -39 -24 Q -25 0 -39 24";
/** Where a straight input at height y meets the concave OR back (the quadratic's x at that y). */
const orBackX = (y, back = -30) => { const t = (y + 24) / 48; return back + 28 * t * (1 - t); };

const inputs = (xAt) => [wire(-30 - STUB - 6, -12, xAt(-12), -12), wire(-30 - STUB - 6, 12, xAt(12), 12)];

