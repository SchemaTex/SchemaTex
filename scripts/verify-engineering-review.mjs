import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { chromium } from 'playwright';
import { renderResult } from '../dist/index.js';
const base = new URL('../preview/engineering-review/', import.meta.url);
const cases = JSON.parse(await readFile(new URL('after/results.json', base), 'utf8'));
assert.deepEqual(cases.map(c => c.id), ['logic']);
const source = await readFile(new URL('logic.sx', base), 'utf8');
const result = renderResult(source, { type: 'logic' });
assert.equal(result.svg, await readFile(new URL('after/logic.svg', base), 'utf8'));
assert.equal(result.status, cases[0].status);
assert.equal(createHash('sha256').update(source).digest('hex'), cases[0].sourceHash);
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1536, height: 1000 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:5173/preview/engineering-review.html');
  await page.waitForSelector('body[data-ready=true]');
  await page.evaluate(() => document.fonts.ready);
  await page.waitForFunction(() => [...document.querySelectorAll('.comparison img')].every(i => i.complete && i.naturalWidth));
  assert.equal(await page.locator('.case').count(), 1);
  assert.equal(await page.locator('.comparison img').count(), 3);
  assert.equal(await page.locator('.comparison > :nth-child(2)').getAttribute('class'), 'panel panel-ideal');
  assert.equal(await page.locator('#opamp, #pid, #linked, #breadboard, .linked-demo').count(), 0);
  const image = page.locator('.panel-ideal .image-button');
  await image.focus(); await page.keyboard.press('Enter');
  assert(await page.locator('#viewer').evaluate(d => d.open));
  await page.keyboard.press('Escape');
  assert(await page.locator('#viewer').evaluate(d => !d.open));
  await page.evaluate(() => document.activeElement.blur());
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert(await page.evaluate(() => !/[\u3400-\u9fff]/.test(document.body.innerText)));
  await page.locator('#logic').screenshot({ path: new URL('logic-comparison.png', base).pathname });
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.locator('#logic').scrollIntoViewIfNeeded();
  await page.screenshot({ path: '/tmp/schematex-logic-only-mobile.png' });
  assert.equal(errors.length, 0);
  console.log('PASS: exact Logic renderer replay; three images; ideal second; keyboard/dialog; desktop/mobile; no page errors; non-Logic sections removed.');
} finally { await browser.close(); }
